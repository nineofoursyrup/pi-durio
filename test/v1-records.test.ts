// ── scenario 6: improve report and decisions ─────────────────────────────────

test('improve report exists with 2 candidates (state: complete)', () => {
  // improve.report is in host records, not in improveFacts (which only scans decision kinds)
  let reportData: any = null;
  for (const ref of records(dataRoot, { kinds: ['improve.report'] })) {
    const data = decode(dataRoot, ref) as any;
    if (data.id === names['improve.report']) { reportData = data; break; }
  }
  assert.ok(reportData, 'improve.report fact should exist in host records');
  assert.equal(reportData.candidates.length, 2, 'should have 2 candidates');
  assert.equal(reportData.state, 'complete', 'report state should be complete');
});

test('candidate-1 has multiple decisions: defer, validate-only, execute-declared-scope', () => {
  const defer    = readImproveDecision(dataRoot, names['improve.decision-defer']!);
  const validate = readImproveDecision(dataRoot, names['improve.decision-validate']!);
  const execute  = readImproveDecision(dataRoot, names['improve.decision-execute']!);
  assert.equal(defer.decision.selections[0].mode,    'defer');
  assert.equal(validate.decision.selections[0].mode, 'validate-only');
  assert.equal(execute.decision.selections[0].mode,  'execute-declared-scope');
  // All three target the same candidate
  const cid = defer.decision.selections[0].candidateId;
  assert.equal(validate.decision.selections[0].candidateId, cid);
  assert.equal(execute.decision.selections[0].candidateId,  cid);
});

test('validate-only decision: writeback is not-written (validation passed, no file change)', () => {
  const validate = readImproveDecision(dataRoot, names['improve.decision-validate']!);
  const writeback = (validate as any).writeback ?? (validate as any).groups?.[0]?.writeback;
  assert.equal(writeback, 'not-written');
});

test('execute decision: writeback is written (candidate was applied)', () => {
  const execute = readImproveDecision(dataRoot, names['improve.decision-execute']!);
  assert.equal((execute as any).writeback, 'written');
});

test('do-not-suggest suppression is recorded and findable by ID', () => {
  const suppressions = listImproveSuppressions(dataRoot);
  assert.ok(suppressions.length >= 1, 'at least one suppression should exist');
  const supp = suppressions.find((s: any) => s.id === names['improve.suppression']);
  assert.ok(supp, 'the named suppression should be findable');
});

// ── scenario 7: frozen queue items ───────────────────────────────────────────

test('frozen follow-up, compact, and improve-batch are in the queue', () => {
  const queue = readQueue(dataRoot);
  const frozen = queue.items.filter((i: any) => i.status === 'frozen');
  const ids = frozen.map((i: any) => i.requestId);
  assert.ok(ids.includes('frozen-follow'),   'frozen-follow should be queued');
  assert.ok(ids.includes('frozen-compact'),  'frozen-compact should be queued');
  assert.ok(ids.includes('frozen-improve'),  'frozen-improve should be queued');
});

// ── scenario 8: eval plan with USD price + absolute δ ─────────────────────────

test('eval plan fixture-eval-plan-1 has USD price and non-null comparison delta', () => {
  const facts = evalFacts(dataRoot, names['eval.plan']);
  const planFact = facts.find((f: any) => f.kind === 'eval.plan');
  assert.ok(planFact, 'eval.plan fact should exist');
  const plan = planFact!.data as any;
  assert.equal(plan.price.currency, 'USD', 'price should be USD');
  assert.ok(plan.comparison, 'plan should have a comparison');
  assert.notEqual(plan.comparison.objective.delta, null, 'comparison delta should be non-null (absolute δ)');
  assert.ok(plan.trials.length > 0, 'plan should have at least one trial');
});

test('eval plan has at least one eval.trial-started fact', () => {
  const facts = evalFacts(dataRoot, names['eval.plan']);
  const trialFacts = facts.filter((f: any) => f.kind === 'eval.trial-started');
  assert.ok(trialFacts.length >= 1, 'at least one eval.trial-started should exist');
});

// ── no lock acquisition ────────────────────────────────────────────────────────

test('watermark reads without error (confirms no exclusive lock was needed)', () => {
  const wm = watermark(dataRoot);
  assert.ok(typeof wm === 'number' && wm > 0, 'watermark should be a positive integer');
});
